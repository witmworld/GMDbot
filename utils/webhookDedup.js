// Идемпотентность /payment/webhook — в памяти процесса, без внешнего
// хранилища (Задача 22).
//
// Изначально (Задача 21) служебные записи 'WH_' + sign писались в Fillout
// COUPON-таблицу. Отказались: таблица бизнесовая, её же читает
// findCouponByCode при проверке купона клиентом, и записи с пустыми
// 'Скидка %'/'Действует до' задевали эту проверку. Плюс таблица
// бесконтрольно росла — очистки не было.
//
// Окно хранения — 24 часа. Обоснование не придумано, а взято из
// документации AllPay (allpay_api_reference_llm.md, раздел 3.2 Payment
// Webhook): повторная доставка идёт до 10 попыток с возрастающим
// интервалом, последняя попытка — в пределах суток после первой. Дальше
// повторов ждать не от чего.
//
// Ограничение, принятое сознательно, а не недосмотр: хранилище живёт
// только в памяти процесса. При рестарте (деплой, краш, ручной рестарт
// на Railway) карта обнуляется — вебхук-повтор, пришедший ПОСЛЕ рестарта,
// будет обработан как новый платёж и кабала выпишется повторно. Раз в
// дедуп-окно это не защита от каждого возможного сценария, а защита от
// конкретно подтверждённого паттерна (Задача 20): AllPay повторяет
// доставку внутри одного и того же (обычно не перезапускаемого) процесса.

const DEDUP_WINDOW_MS = 24 * 60 * 60 * 1000 // сутки — см. обоснование выше

const processedWebhooks = new Map() // sign -> время обработки (мс, Date.now())

// Чистка при обращении, отдельный таймер намеренно не заводим.
function purgeExpired() {
  const now = Date.now()
  for (const [sign, ts] of processedWebhooks) {
    if (now - ts > DEDUP_WINDOW_MS) processedWebhooks.delete(sign)
  }
}

export function isWebhookProcessed(sign) {
  if (!sign) return false
  purgeExpired()
  return processedWebhooks.has(sign)
}

export function markWebhookProcessed(sign) {
  if (!sign) return
  purgeExpired()
  processedWebhooks.set(sign, Date.now())
}
